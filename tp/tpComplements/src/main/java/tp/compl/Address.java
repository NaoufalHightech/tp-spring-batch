package tp.compl;
public class Address {
  private String countryCode, zip, town, street, number, complements;
  public String getCountryCode(){return countryCode;} public void setCountryCode(String v){countryCode=v;}
  public String getZip(){return zip;} public void setZip(String v){zip=v;}
  public String getTown(){return town;} public void setTown(String v){town=v;}
  public String getStreet(){return street;} public void setStreet(String v){street=v;}
  public String getNumber(){return number;} public void setNumber(String v){number=v;}
  public String getComplements(){return complements;} public void setComplements(String v){complements=v;}
}
